#!/usr/bin/env bash
# Convert the TComm fonts to LVGL 8 C files with lv_font_conv 1.5.3 (needs Node's npx).
# Run from the firmware folder in Git Bash:  bash tools/make_fonts.sh
# Jost only ships as a variable font, so cut the ExtraBold weight first (needs fonttools):
#   python -P -m fontTools.varLib.instancer "assets/fonts/src/jost/Jost[wght].ttf" wght=800 \
#       -o assets/fonts/src/jost/Jost-ExtraBold-800.ttf
set -euo pipefail
cd "$(dirname "$0")/.."

SRC=assets/fonts/src
OUT=tcomm/src/ui/fonts
RANGE="0x20-0x7E,0xB0,0xB7,0x2013,0x2026"  # ASCII, degree, middle dot, en dash, ellipsis
mkdir -p "$OUT"

names=()
convert() {  # font file, base name, sizes...
  convert_range "$1" "$2" "$RANGE" "" "${@:3}"
}
convert_range() {  # font file, base name, glyph range, name suffix, sizes...
  local font=$1 base=$2 range=$3 suffix=$4; shift 4
  for size in "$@"; do
    local name="${base}_${size}${suffix}"
    npx --yes lv_font_conv@1.5.3 --font "$SRC/$font" -r "$range" --size "$size" --bpp 4 \
      --format lvgl --no-compress --lv-font-name "$name" -o "$OUT/$name.c"
    # The generated include assumes an "lvgl/" folder; the Arduino library and the simulator expose plain lvgl.h.
    sed -i 's|#include "lvgl/lvgl.h"|#include "lvgl.h"|' "$OUT/$name.c"
    names+=("$name")
    echo "$name"
  done
}

convert jost/Jost-ExtraBold-800.ttf font_jost_800 64 54 50 44 36 30 28 27 24 23
convert atkinson/AtkinsonHyperlegible-Bold.ttf font_atk_bold 11 12 13 14 15 16 18 19 20 21 22 23 24 26
# The calendar's date numerals (day view, week view, today's pill): digits only, to save flash and
# the PSRAM the program image is copied into.
convert_range jost/Jost-ExtraBold-800.ttf font_jost_800 "0x30-0x39" _num 76 22 21
convert atkinson/AtkinsonHyperlegible-Regular.ttf font_atk_reg 16 20

{
  echo "// Generated by tools/make_fonts.sh. Jost and Atkinson Hyperlegible, SIL Open Font License 1.1"
  echo "// (licence files in assets/fonts/src)."
  echo "#pragma once"
  echo '#include "lvgl.h"'
  echo
  for n in "${names[@]}"; do echo "LV_FONT_DECLARE($n);"; done
} > "$OUT/fonts.h"
